-- Kestrel Market: fictional mid-size retailer (online + physical stores).
--
-- Only primary keys, UNIQUE constraints and one partial unique index exist.
-- Foreign key columns are NOT indexed on purpose (PostgreSQL does not index
-- them automatically): finding and fixing that is part of the lab.

DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

-- ───────────────────────── HR ─────────────────────────

CREATE TABLE departments (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE stores (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      text    NOT NULL UNIQUE,
    city      text    NOT NULL,
    state     char(2) NOT NULL,
    opened_at date    NOT NULL,
    closed_at date,
    CHECK (closed_at IS NULL OR closed_at > opened_at)
);

CREATE TABLE employees (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name       text          NOT NULL,
    last_name        text          NOT NULL,
    email            text          NOT NULL UNIQUE,
    job_title        text          NOT NULL,
    department_id    integer       NOT NULL REFERENCES departments (id),
    store_id         integer       REFERENCES stores (id),     -- NULL = headquarters
    manager_id       integer       REFERENCES employees (id),  -- NULL = the CEO
    salary           numeric(10,2) NOT NULL CHECK (salary > 0),
    hire_date        date          NOT NULL,
    termination_date date,                                      -- NULL = still employed
    CHECK (termination_date IS NULL OR termination_date > hire_date)
);

-- ─────────────────────── Catalog ───────────────────────

CREATE TABLE categories (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      text    NOT NULL,
    parent_id integer REFERENCES categories (id),  -- NULL = top-level section
    UNIQUE (parent_id, name)
);

CREATE TABLE products (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             text          NOT NULL UNIQUE,
    name            text          NOT NULL,
    brand           text          NOT NULL,
    category_id     integer       NOT NULL REFERENCES categories (id),  -- always a leaf category
    price           numeric(10,2) NOT NULL CHECK (price > 0),
    cost            numeric(10,2) NOT NULL CHECK (cost > 0),
    created_at      timestamptz   NOT NULL,
    discontinued_at timestamptz,
    CHECK (cost < price),
    CHECK (discontinued_at IS NULL OR discontinued_at > created_at)
);

-- ──────────────────────── Sales ────────────────────────

CREATE TABLE customers (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name text        NOT NULL,
    last_name  text        NOT NULL,
    email      text        NOT NULL UNIQUE,
    phone      text,                       -- optional
    created_at timestamptz NOT NULL
);

CREATE TABLE addresses (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES customers (id),
    street      text    NOT NULL,
    city        text    NOT NULL,
    state       char(2) NOT NULL,
    zip_code    text    NOT NULL,
    is_default  boolean NOT NULL DEFAULT false
);
-- At most one default address per customer.
CREATE UNIQUE INDEX addresses_one_default_per_customer
    ON addresses (customer_id) WHERE is_default;

CREATE TABLE orders (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id         integer     NOT NULL REFERENCES customers (id),
    channel             text        NOT NULL CHECK (channel IN ('online', 'in_store')),
    store_id            integer     REFERENCES stores (id),     -- in_store only
    employee_id         integer     REFERENCES employees (id),  -- in_store only: the salesperson
    shipping_address_id integer     REFERENCES addresses (id),  -- online only
    status              text        NOT NULL
        CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled')),
    ordered_at          timestamptz NOT NULL,
    shipped_at          timestamptz,
    delivered_at        timestamptz,
    CHECK (
        (channel = 'in_store' AND store_id IS NOT NULL AND employee_id IS NOT NULL
                              AND shipping_address_id IS NULL)
     OR (channel = 'online'   AND store_id IS NULL AND employee_id IS NULL
                              AND shipping_address_id IS NOT NULL)
    ),
    CHECK (shipped_at IS NULL OR shipped_at >= ordered_at),
    CHECK (delivered_at IS NULL OR delivered_at >= COALESCE(shipped_at, ordered_at))
);

CREATE TABLE order_items (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   integer       NOT NULL REFERENCES orders (id),
    product_id integer       NOT NULL REFERENCES products (id),
    quantity   integer       NOT NULL CHECK (quantity > 0),
    unit_price numeric(10,2) NOT NULL CHECK (unit_price > 0),
    discount   numeric(3,2)  NOT NULL DEFAULT 0 CHECK (discount >= 0 AND discount <= 0.5),
    UNIQUE (order_id, product_id)
);

CREATE TABLE payments (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer       NOT NULL REFERENCES orders (id),
    method   text          NOT NULL
        CHECK (method IN ('credit_card', 'debit_card', 'paypal', 'gift_card', 'cash')),
    amount   numeric(10,2) NOT NULL CHECK (amount > 0),
    status   text          NOT NULL CHECK (status IN ('completed', 'failed', 'refunded')),
    paid_at  timestamptz   NOT NULL
);

COMMENT ON TABLE  employees            IS 'Staff. store_id NULL = headquarters; manager_id NULL = CEO.';
COMMENT ON TABLE  categories           IS 'Category tree with mixed depth (2 or 3 levels). Products hang from leaves only.';
COMMENT ON TABLE  orders               IS 'Order total is NOT stored: sum of round(quantity * unit_price * (1 - discount), 2) over its items.';
COMMENT ON COLUMN order_items.unit_price IS 'Product price at the time of the order (prices never changed in this dataset).';
COMMENT ON TABLE  payments             IS 'An order can have a failed attempt before the completed one. Refunded = cancelled after paying.';
